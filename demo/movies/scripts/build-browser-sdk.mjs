#!/usr/bin/env node
/**
 * Bundle the JS SDK and its browser dependencies into the static similarity demo.
 *
 * The demo must not require node_modules at page runtime. Run this after `pnpm sdk:build` when the
 * SDK changes; `quickstart.sh` runs it so the local demo always uses the current bundle.
 */
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const ENTRY = join(ROOT, "sdk/client/js/dist/index.mjs");
const OUTPUT = join(ROOT, "demo/movies/browser/vendor/gleaph-sdk.mjs");

function esbuildBinary() {
  const direct = join(ROOT, "node_modules/.bin/esbuild");
  if (existsSync(direct)) return direct;
  const pnpm = join(ROOT, "node_modules/.pnpm");
  for (const entry of (existsSync(pnpm) ? readdirSync(pnpm) : [])) {
    if (!entry.startsWith("esbuild@")) continue;
    const candidate = join(pnpm, entry, "node_modules/esbuild/bin/esbuild");
    if (existsSync(candidate)) return candidate;
  }
  throw new Error("esbuild not found; run pnpm install at the workspace root");
}

if (!existsSync(ENTRY)) {
  throw new Error(`${ENTRY} is missing; run \`pnpm sdk:build\` first`);
}
execFileSync(
  esbuildBinary(),
  [
    ENTRY,
    "--bundle",
    "--format=esm",
    "--platform=browser",
    "--target=es2022",
    "--minify",
    "--banner:js=/* generated by demo/movies/scripts/build-browser-sdk.mjs; do not edit */",
    `--outfile=${OUTPUT}`,
  ],
  { stdio: "inherit", cwd: ROOT },
);
console.log(`wrote ${OUTPUT}`);
